test("statistics event and region chips support keyboard selection, region memory and phone widths", async ({ page }) => {
	const season = makeAuditSeason("Themed event picker");
	const international = season.phases.find(phase => phase.kind === "international" && phase.event === "msi")!;
	const tournament = { ...Object.values(season.tournaments)[0], id: "selector-msi" };
	season.tournaments[tournament.id] = tournament;
	international.tournamentIds = [tournament.id];
	const spring = season.phases.find(phase => phase.kind === "split" && phase.split === "spring")!;
	spring.tournamentIds = season.phases[0].tournamentIds.map(id => {
		const copy = { ...season.tournaments[id], id: `${id}-spring` };
		season.tournaments[copy.id] = copy;
		return copy.id;
	});
	await page.setViewportSize({ width: 1440, height: 900 });
	await page.addInitScript(season => {
		if (!localStorage.getItem("draftsim-store")) localStorage.setItem("draftsim-store", JSON.stringify({ version: 7, state: { season, seasonViewOpen: true } }));
	}, season);
	await page.goto("/");
	const toggle = page.getByRole("button", { name: /^Event Statistics/ });
	await toggle.click();
	const events = page.getByRole("radiogroup", { name: "Event", exact: true });
	const regions = page.getByRole("radiogroup", { name: "Region", exact: true });
	await expect(events.getByRole("radio")).toHaveCount(3);
	await expect(events.getByRole("radio", { name: "Winter Split" }).locator("svg")).toBeVisible();
	await expect(events.getByRole("radio", { name: "MSI", exact: true }).locator("img")).toHaveAttribute("src", "/league-logos/msi.png");
	expect(await regions.getByRole("radio").evaluateAll(buttons => buttons.map(button => button.getAttribute("aria-label")))).toEqual(["LCK", "LPL", "LEC", "LCS", "CBLOL", "LCP"]);
	await regions.getByRole("radio", { name: "LPL", exact: true }).click();
	await events.getByRole("radio", { name: "Winter Split" }).focus();
	await events.getByRole("radio", { name: "Winter Split" }).press("ArrowRight");
	await expect(events.getByRole("radio", { name: "Spring Split" })).toBeFocused();
	await expect(events.getByRole("radio", { name: "Spring Split" })).toHaveAttribute("aria-checked", "true");
	await expect(regions.getByRole("radio", { name: "LPL", exact: true })).toHaveAttribute("aria-checked", "true");
	await events.getByRole("radio", { name: "Spring Split" }).press("End");
	await expect(regions).toHaveCount(0);
	await expect(page.getByRole("region", { name: `${international.label} event statistics`, exact: true })).toBeVisible();
	await events.getByRole("radio", { name: "MSI", exact: true }).press("Home");
	await expect(regions.getByRole("radio", { name: "LPL", exact: true })).toHaveAttribute("aria-checked", "true");
	await page.screenshot({ path: "test-results/playwright/event-picker-desktop.png" });
	await page.setViewportSize({ width: 390, height: 844 });
	await events.scrollIntoViewIfNeeded();
	await expect(events.getByRole("radio").first()).toHaveCSS("font-family", /Inter/);
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
	await page.screenshot({ path: "test-results/playwright/event-picker-mobile.png" });
});
