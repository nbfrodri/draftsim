	await expect(panel.locator('td[title="0 games with recorded KDA"]').first()).toHaveText("—");
	await panel.getByRole("combobox", { name: "Ranking checkpoint" }).click();
	await expect(panel.getByRole("listbox", { name: "Ranking checkpoint" }).getByRole("option").nth(1)).toContainText("1 game");
	await panel.getByRole("listbox", { name: "Ranking checkpoint" }).getByRole("option").nth(1).click();
	await expect(panel).toContainText("1 game at this checkpoint");
	await expect(panel).toContainText("Provisional · 1/3 rated games");
	await panel.getByRole("combobox", { name: "Ranking checkpoint" }).click();
	await panel.getByRole("option", { name: "Current / final standings", exact: true }).click();
	const sort = panel.getByRole("combobox", { name: "Player sort" });
	await sort.click();
	await panel.getByRole("option", { name: "Games", exact: true }).click();
	await expect(sort).toContainText("Games");
